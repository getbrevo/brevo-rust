pub use crate::prelude::*;

#[derive(Debug, Clone, Serialize, Deserialize, Default, PartialEq, Eq, Hash)]
pub struct PostConversationsMessagesRequest {
    /// Agent's email address. When sending messages from a standalone system, it's hard to maintain a 1-to-1 relationship between the users of both systems. In this case, an agent can be specified by their email address.
    #[serde(rename = "agentEmail")]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub agent_email: Option<String>,
    /// Agent ID. It can be found on the agent's page or received <a href="https://developers.brevo.com/docs/conversations-webhooks">from a webhook</a>. Alternatively, you can use `agentEmail` + `agentName` + `receivedFrom` instead (all 3 fields required).
    #[serde(rename = "agentId")]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub agent_id: Option<String>,
    /// Agent's name.
    #[serde(rename = "agentName")]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub agent_name: Option<String>,
    /// Mark your messages to distinguish messages created by you from the others.
    #[serde(rename = "receivedFrom")]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub received_from: Option<String>,
    /// Message text.
    #[serde(default)]
    pub text: String,
    /// Visitor's ID received <a href="https://developers.brevo.com/docs/conversations-webhooks">from a webhook</a> or generated by you to <a href="https://developers.brevo.com/docs/customize-the-widget#identifying-existing-users">bind an existing user account to Conversations</a>.
    #[serde(rename = "visitorId")]
    #[serde(default)]
    pub visitor_id: String,
}

impl PostConversationsMessagesRequest {
    pub fn builder() -> PostConversationsMessagesRequestBuilder {
        <PostConversationsMessagesRequestBuilder as Default>::default()
    }
}

#[derive(Clone, PartialEq, Default, Debug)]
#[non_exhaustive]
pub struct PostConversationsMessagesRequestBuilder {
    agent_email: Option<String>,
    agent_id: Option<String>,
    agent_name: Option<String>,
    received_from: Option<String>,
    text: Option<String>,
    visitor_id: Option<String>,
}

impl PostConversationsMessagesRequestBuilder {
    pub fn agent_email(mut self, value: impl Into<String>) -> Self {
        self.agent_email = Some(value.into());
        self
    }

    pub fn agent_id(mut self, value: impl Into<String>) -> Self {
        self.agent_id = Some(value.into());
        self
    }

    pub fn agent_name(mut self, value: impl Into<String>) -> Self {
        self.agent_name = Some(value.into());
        self
    }

    pub fn received_from(mut self, value: impl Into<String>) -> Self {
        self.received_from = Some(value.into());
        self
    }

    pub fn text(mut self, value: impl Into<String>) -> Self {
        self.text = Some(value.into());
        self
    }

    pub fn visitor_id(mut self, value: impl Into<String>) -> Self {
        self.visitor_id = Some(value.into());
        self
    }

    /// Consumes the builder and constructs a [`PostConversationsMessagesRequest`].
    /// This method will fail if any of the following fields are not set:
    /// - [`text`](PostConversationsMessagesRequestBuilder::text)
    /// - [`visitor_id`](PostConversationsMessagesRequestBuilder::visitor_id)
    pub fn build(self) -> Result<PostConversationsMessagesRequest, BuildError> {
        Ok(PostConversationsMessagesRequest {
            agent_email: self.agent_email,
            agent_id: self.agent_id,
            agent_name: self.agent_name,
            received_from: self.received_from,
            text: self.text.ok_or_else(|| BuildError::missing_field("text"))?,
            visitor_id: self
                .visitor_id
                .ok_or_else(|| BuildError::missing_field("visitor_id"))?,
        })
    }
}
