pub use crate::prelude::*;

#[derive(Debug, Clone, Serialize, Deserialize, Default, PartialEq, Eq, Hash)]
pub struct PostConversationsPushedMessagesRequest {
    /// Agent ID. It can be found on the agent's page or received <a href="https://developers.brevo.com/docs/conversations-webhooks">from a webhook</a>.
    #[serde(rename = "agentId")]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub agent_id: Option<String>,
    /// Group ID. It can be found on the group's page.
    #[serde(rename = "groupId")]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub group_id: Option<String>,
    /// Message text.
    #[serde(default)]
    pub text: String,
    /// Visitor's ID received <a href="https://developers.brevo.com/docs/conversations-webhooks">from a webhook</a> or generated by you to <a href="https://developers.brevo.com/docs/customize-the-widget#identifying-existing-users">bind an existing user account to Conversations</a>.
    #[serde(rename = "visitorId")]
    #[serde(default)]
    pub visitor_id: String,
}

impl PostConversationsPushedMessagesRequest {
    pub fn builder() -> PostConversationsPushedMessagesRequestBuilder {
        <PostConversationsPushedMessagesRequestBuilder as Default>::default()
    }
}

#[derive(Clone, PartialEq, Default, Debug)]
#[non_exhaustive]
pub struct PostConversationsPushedMessagesRequestBuilder {
    agent_id: Option<String>,
    group_id: Option<String>,
    text: Option<String>,
    visitor_id: Option<String>,
}

impl PostConversationsPushedMessagesRequestBuilder {
    pub fn agent_id(mut self, value: impl Into<String>) -> Self {
        self.agent_id = Some(value.into());
        self
    }

    pub fn group_id(mut self, value: impl Into<String>) -> Self {
        self.group_id = Some(value.into());
        self
    }

    pub fn text(mut self, value: impl Into<String>) -> Self {
        self.text = Some(value.into());
        self
    }

    pub fn visitor_id(mut self, value: impl Into<String>) -> Self {
        self.visitor_id = Some(value.into());
        self
    }

    /// Consumes the builder and constructs a [`PostConversationsPushedMessagesRequest`].
    /// This method will fail if any of the following fields are not set:
    /// - [`text`](PostConversationsPushedMessagesRequestBuilder::text)
    /// - [`visitor_id`](PostConversationsPushedMessagesRequestBuilder::visitor_id)
    pub fn build(self) -> Result<PostConversationsPushedMessagesRequest, BuildError> {
        Ok(PostConversationsPushedMessagesRequest {
            agent_id: self.agent_id,
            group_id: self.group_id,
            text: self.text.ok_or_else(|| BuildError::missing_field("text"))?,
            visitor_id: self
                .visitor_id
                .ok_or_else(|| BuildError::missing_field("visitor_id"))?,
        })
    }
}
